-- This file sources other files in `hyprland` and `custom` folders
-- You wanna add your stuff in files in `custom`

-- Internal stuff --
require("hyprland.lib")
require("hyprland.services")

-- Environment variables --
require("hyprland.env")
if is_file_exists(HOME .. "/.config/hypr/custom/env.lua") then
    require("custom.env")
end

-- Default configurations --
require("hyprland.execs")
require("hyprland.general")
require("hyprland.rules")
require("hyprland.colors")
require("hyprland.keybinds")

-- Custom configurations --
if is_file_exists(HOME .. "/.config/hypr/custom/execs.lua") then
    require("custom.execs")
end
if is_file_exists(HOME .. "/.config/hypr/custom/general.lua") then
    require("custom.general")
end
if is_file_exists(HOME .. "/.config/hypr/custom/rules.lua") then
    require("custom.rules")
end
if is_file_exists(HOME .. "/.config/hypr/custom/keybinds.lua") then
    require("custom.keybinds")
end

-- nwg-displays support --
if is_file_exists(HOME .. "/.config/hypr/workspaces.lua") then
    require("workspaces")
end
if is_file_exists(HOME .. "/.config/hypr/monitors.lua") then
    require("monitors")
end

-- Settings app --
-- Options persisted by the settings app. Loaded after custom/* and monitors so
-- the app's choices win over hand-written defaults, and before the shell
-- overrides so Game Mode (which writes shellOverrides/main.lua) still wins
-- while it is active.
if is_file_exists(HOME .. "/.config/hypr/custom/shell-settings.lua") then
    require("custom.shell-settings")
end
-- Animations and curves chosen in the settings app, generated by
-- scripts/settings/animationsgen.py. Loaded after shell-settings so they win
-- over general.lua, and before the shell overrides. pcall keeps a broken file
-- (a Lua error) from stopping the rest of this config, above all Game Mode's
-- overrides below: Hyprland lists the error in its config errors, keeps the
-- animations from general.lua for the lines that did not run, and the settings
-- app, which checks its first write against `hyprctl -j animations`, reports it.
if is_file_exists(HOME .. "/.config/hypr/custom/shell-animations.lua") then
    pcall(require, "custom.shell-animations")
end

-- Shell overrides --
require("hyprland.shellOverrides.main")
